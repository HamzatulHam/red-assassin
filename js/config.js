/* ---------- Служебные функции (используются везде) ---------- */

// случайное число от a до b
RA.rand = function (a, b) { return a + Math.random() * (b - a); };

// срабатывание с вероятностью p (0..1)
RA.chance = function (p) { return Math.random() < p; };

// детерминированный «шум» 0..1 — для декораций, чтобы горы не прыгали
RA.hash = function (n) {
  const s = Math.sin(n * 127.1 + 311.7) * 43758.5453;
  return s - Math.floor(s);
};

// скруглённый прямоугольник: только НАЧАТЬ путь, fill/stroke на вызывающем
RA.rr = function (ctx, x, y, w, h, r) {
  r = Math.min(r, w / 2, h / 2);
  ctx.beginPath();
  ctx.moveTo(x + r, y);
  ctx.arcTo(x + w, y, x + w, y + h, r);
  ctx.arcTo(x + w, y + h, x, y + h, r);
  ctx.arcTo(x, y + h, x, y, r);
  ctx.arcTo(x, y, x + w, y, r);
  ctx.closePath();
};

// безопасный localStorage (работает и с file://)
RA.lsGet = function (key, def) {
  try {
    const v = localStorage.getItem(key);
    return v === null ? def : JSON.parse(v);
  } catch (e) { return def; }
};
RA.lsSet = function (key, val) {
  try { localStorage.setItem(key, JSON.stringify(val)); } catch (e) {}
};
